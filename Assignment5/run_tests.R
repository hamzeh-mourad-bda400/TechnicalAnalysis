# Run in RStudio after extracting all scripts into one folder.
for (f in c("sma.R","ema.R","macd.R","stdev.R","linreg.R","rsi.R","stoch_rsi.R","crossover.R","crossunder.R")) source(f)
close <- c(10,12,15,20,18,22,25,24,21,23,26,22,28,30,27,29,32,31,34,33)
stopifnot(isTRUE(all.equal(sma(c(1,2,3,4),2), c(1.5,2.5,3.5))))
stopifnot(isTRUE(all.equal(ema(c(10,12,14),3),c(10,11,12.5))))
stopifnot(isTRUE(all.equal(stdev(c(2,4,6)),sqrt(8/3))))
stopifnot(isTRUE(all.equal(linreg(c(2,4,6,8),4,0)$slope,2)))
stopifnot(length(rsi(close,5))==length(close))
stopifnot(all(rsi(close,5)[!is.na(rsi(close,5))] >= 0 & rsi(close,5)[!is.na(rsi(close,5))] <= 100))
stopifnot(length(stoch_rsi(close,5,3,3)$k_line)==length(close))
stopifnot(length(macd(close,3,5,2)$histogram)==length(close))
stopifnot(identical(crossover(c(1,3,1),c(2,2,2)),c("None","Up","Down")))
stopifnot(identical(crossunder(c(3,1),c(2,2)),c("None","True")))
cat("All 10 sample checks passed.\n")
